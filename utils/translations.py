class LocalizedDict(dict):
    """Dictionary that returns manual translations and safe cached fallbacks."""

    def __init__(self, values: dict, language: str, manual_keys: set | None = None):
        super().__init__(values)
        self.language = language or "English"
        self.manual_keys = manual_keys or set()

    def _localize(self, key, value):
        if not isinstance(value, str):
            return value
        if not self.language or self.language.lower() == "english":
            return value
        if key in self.manual_keys:
            return value
        return translate_text(value, self.language, context="RuralFinance app UI label", live=False)

    def get(self, key, default=None):
        return self._localize(key, super().get(key, default))

    def __getitem__(self, key):
        return self._localize(key, super().__getitem__(key))

