def get_ui(language: str) -> dict:
    """Return UI string dict for *language*. Falls back to English for unsupported langs."""
    language = normalize_app_language(language)
    code = _LANG_CODE.get(language, "en")
    base = _T.get(code, _T["en"])
    extra_en = _EXTRA_T.get("en", {})
    extra_lang = _EXTRA_T.get(code, {})
    # Merge: English base → extra English → language base → extra language
    has_manual_language = code != "en" and code in _T
    manual_keys = set(base.keys()) if has_manual_language else set()
    if code != "en" and code in _EXTRA_T:
        manual_keys.update(extra_lang.keys())
    return LocalizedDict({**_T["en"], **extra_en, **base, **extra_lang}, language, manual_keys)
